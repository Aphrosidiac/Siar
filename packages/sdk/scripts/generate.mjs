#!/usr/bin/env node
/**
 * Generates the typed client from the Siar OpenAPI contract.
 *
 *   node scripts/generate.mjs
 *
 * Reads  ../contract/openapi.json and ../contract/src/types.ts (openapi-typescript output)
 * Writes src/contract.ts   — a verbatim copy of the contract types, so the published package
 *                             carries its own types and never depends on @siar/contract.
 *        src/generated.ts  — the operation table, per-operation type helpers and one method per
 *                             operation, grouped by the operationId prefix (post.create → siar.post.create).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contractDir = join(here, '..', '..', 'contract');
const srcDir = join(here, '..', 'src');

const spec = JSON.parse(readFileSync(join(contractDir, 'openapi.json'), 'utf8'));
const types = readFileSync(join(contractDir, 'src', 'types.ts'), 'utf8');

const BANNER = '// Generated by scripts/generate.mjs from packages/contract. Do not edit by hand.\n';

writeFileSync(join(srcDir, 'contract.ts'), `${BANNER}/* eslint-disable */\n${types}`);

const METHODS = ['get', 'put', 'post', 'patch', 'delete'];
const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op?.operationId) continue;
    const params = [...(item.parameters ?? []), ...(op.parameters ?? [])];
    const pathParams = params.filter(p => p.in === 'path').map(p => p.name);
    const queryParams = params.filter(p => p.in === 'query');
    const content = op.requestBody?.content ?? {};
    const body = content['application/json'] ? 'json' : content['multipart/form-data'] ? 'multipart' : null;
    ops.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      pathParams,
      query: queryParams.length > 0,
      queryRequired: queryParams.some(p => p.required),
      queryNames: queryParams.map(p => p.name),
      body,
      summary: op.summary ?? '',
      description: op.description ?? '',
      deprecated: !!op.deprecated,
    });
  }
}
ops.sort((a, b) => a.id.localeCompare(b.id));

const ids = new Set();
for (const o of ops) {
  if (ids.has(o.id)) throw new Error(`Duplicate operationId ${o.id}`);
  ids.add(o.id);
  for (const seg of o.id.split('.')) if (!/^[A-Za-z_$][\w$]*$/.test(seg)) throw new Error(`operationId segment "${seg}" in ${o.id} is not an identifier`);
}

const paginated = ops.filter(o => o.queryNames.includes('offset') && o.queryNames.includes('limit')).map(o => o.id);

// Build the namespace tree: 'misc.youtube.getChannelPlaylist' → misc → youtube → getChannelPlaylist.
const tree = {};
for (const o of ops) {
  const segs = o.id.split('.');
  let node = tree;
  for (const s of segs.slice(0, -1)) {
    node[s] ??= {};
    if (node[s].__op) throw new Error(`${o.id} collides with an operation name`);
    node = node[s];
  }
  const leaf = segs[segs.length - 1];
  if (node[leaf]) throw new Error(`${o.id} collides with a namespace`);
  node[leaf] = { __op: o };
}

const q = s => JSON.stringify(s);
const doc = (o, indent) => {
  const lines = [o.summary || o.id];
  if (o.description && o.description !== o.summary) lines.push('', ...o.description.split('\n'));
  lines.push('', `\`${o.method} ${o.path}\` — operationId \`${o.id}\``);
  if (o.deprecated) lines.push('@deprecated');
  return `${indent}/**\n${lines.map(l => `${indent} * ${l.replace(/\*\//g, '*\\/')}`.trimEnd()).join('\n')}\n${indent} */\n`;
};

/** Parameters of the generated method, in order: path, query, body, options. */
function signature(o) {
  const K = q(o.id);
  const args = [];
  const call = [];
  if (o.pathParams.length) { args.push(`path: PathParams<${K}>`); call.push('path'); }
  if (o.query) { args.push(`query${o.queryRequired ? '' : '?'}: Query<${K}>`); call.push('query'); }
  if (o.body) { args.push(`body: Body<${K}>`); call.push('body'); }
  args.push('options?: RequestOptions');
  return { args: args.join(', '), call: call.length ? `{ ${call.join(', ')} }` : '{}' };
}

function emitInterface(node, indent) {
  let out = '';
  for (const [name, child] of Object.entries(node)) {
    if (child.__op) {
      const o = child.__op;
      const s = signature(o);
      out += doc(o, indent);
      out += `${indent}${name}(${s.args}): Promise<Result<${q(o.id)}>>;\n`;
    } else {
      out += `${indent}${name}: {\n${emitInterface(child, indent + '  ')}${indent}};\n`;
    }
  }
  return out;
}

function emitImpl(node, indent) {
  let out = '';
  for (const [name, child] of Object.entries(node)) {
    if (child.__op) {
      const o = child.__op;
      const s = signature(o);
      out += `${indent}${name}: (${s.args}) => call(${q(o.id)}, ${s.call}, options),\n`;
    } else {
      out += `${indent}${name}: {\n${emitImpl(child, indent + '  ')}${indent}},\n`;
    }
  }
  return out;
}

const table = ops.map(o => {
  const def = { method: o.method, path: o.path, pathParams: o.pathParams, query: o.queryNames, body: o.body };
  return `  ${q(o.id)}: ${JSON.stringify(def)},`;
}).join('\n');

const out = `${BANNER}/* eslint-disable */
import type { operations } from './contract.js';

/** Every operationId in the Siar API (${ops.length} operations). */
export type OperationId = keyof operations;

type Json<C> = C extends { 'application/json': infer B } ? B : C extends { 'multipart/form-data': infer F } ? F : never;
type Success<R> = R extends { 200: infer S } ? S : R extends { 201: infer S } ? S : never;

/** JSON (or multipart) request body of an operation. */
export type Body<K extends OperationId> = operations[K] extends { requestBody?: infer R } ? (R extends { content: infer C } ? Json<C> : never) : never;
/** Query-string parameters of an operation. */
export type Query<K extends OperationId> = operations[K]['parameters'] extends { query?: infer Q } ? Exclude<Q, undefined> : never;
/** Path parameters of an operation, e.g. \`{ id: string }\`. */
export type PathParams<K extends OperationId> = operations[K]['parameters'] extends { path?: infer P } ? Exclude<P, undefined> : never;
/** Successful (2xx) JSON response of an operation. */
export type Result<K extends OperationId> = Success<operations[K]['responses']> extends { content: { 'application/json': infer B } } ? B : unknown;

export interface OperationDef {
  method: 'GET' | 'PUT' | 'POST' | 'PATCH' | 'DELETE';
  path: string;
  pathParams: readonly string[];
  query: readonly string[];
  body: 'json' | 'multipart' | null;
}

/** Method, path and parameter layout of every operation, keyed by operationId. */
export const OPERATIONS: Record<OperationId, OperationDef> = {
${table}
};

/** Operations that page with \`offset\` / \`limit\` — usable with \`siar.paginate()\`. */
export const PAGINATED_OPERATIONS = ${JSON.stringify(paginated)} as const;
export type PaginatedOperationId = (typeof PAGINATED_OPERATIONS)[number];

/** Options accepted by every generated method as its last argument. */
export interface RequestOptions {
  /** Abort the request. */
  signal?: AbortSignal;
  /** Override the client timeout for this request (milliseconds). */
  timeoutMs?: number;
  /** Override the client's maxRetries for this request. */
  maxRetries?: number;
  /**
   * Retry this request on 429/5xx/network errors even though its method is not idempotent
   * (POST, PATCH). Only opt in when repeating the request is safe — e.g. you set a referenceKey.
   */
  retry?: boolean;
  /** Extra headers for this request. */
  headers?: Record<string, string>;
}

export interface CallArgs {
  path?: Record<string, string | number> | object;
  query?: Record<string, unknown> | object;
  body?: unknown;
}

export type Caller = (operationId: OperationId, args: CallArgs, options?: RequestOptions) => Promise<any>;

/** One method per operation, grouped by the operationId prefix. */
export interface SiarResources {
${emitInterface(tree, '  ')}}

export function createResources(call: Caller): SiarResources {
  return {
${emitImpl(tree, '    ')}  };
}
`;

writeFileSync(join(srcDir, 'generated.ts'), out);
console.error(`generated ${ops.length} operations (${paginated.length} paginated) → src/generated.ts, src/contract.ts`);
